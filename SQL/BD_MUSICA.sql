CREATE DATABASE IF NOT EXISTS BD_MUSICA;
USE BD_MUSICA;

	CREATE TABLE IF NOT EXISTS ALBUM (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(255) NOT NULL,
    DATA_LANCAMENTO DATE NOT NULL,
    CAPA VARCHAR(255) NOT NULL,
    QTD_FAIXA VARCHAR(255) NOT NULL,
    FK_CPF_ARTISTA INT 
    );
    
  CREATE TABLE IF NOT EXISTS ARTISTA(
  CPF_CNPJ INT AUTO_INCREMENT PRIMARY KEY,
  NOME VARCHAR(255) NOT NULL,
  EMAIL VARCHAR(100) ,
  TELEFONE VARCHAR(10)
  );
  
 CREATE TABLE IF NOT EXISTS FAIXA(
 ID INT AUTO_INCREMENT PRIMARY KEY,
 NOME VARCHAR(255) NOT NULL,
 CAPA VARCHAR(255) NOT NULL,
 DURACAO VARCHAR(255),
 LETRA VARCHAR(1440) NOT NULL,
 DATE_LANCAMENTO DATE,
 
 );
